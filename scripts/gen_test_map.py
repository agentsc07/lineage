"""Write docs/TEST_COVERAGE.md: for every check in the catalogue, the tests that exercise it.

    uv run python scripts/gen_test_map.py

A test is listed for a check when its source mentions one of the check's finding ids, or imports/calls the check's module or entry function.
This is a map for a reader (and a gap finder), not a proof that each assertion is strong: open the named test to see what it asserts.
"""
from __future__ import annotations

import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from lineage.catalog import CHECKERS, checker_for  # noqa: E402

ID = re.compile(r'["\']((?:PKG|MODEL|DATA|TOOL|PROV|INTEGRITY|INTAKE|POLICY|LLM|CHECK|SCANNER|GPU)\.[A-Z0-9_.]*[A-Z0-9_]?)["\']')
FAKES = re.compile(r"FakeWorker|fake_gpu|MockTransport|monkeypatch\.setattr\(httpx|Stub|fakehub|old_release_hub|create_app")


def tests() -> list[tuple[str, str, str]]:
    out = []
    for p in sorted((ROOT / "tests").rglob("test_*.py")):
        src = p.read_text()
        try:
            tree = ast.parse(src)
        except SyntaxError:
            continue
        for n in ast.walk(tree):
            if isinstance(n, ast.FunctionDef) and n.name.startswith("test_"):
                out.append((p.relative_to(ROOT / "tests").as_posix(), n.name, ast.get_source_segment(src, n) or ""))
    return out


def main() -> None:
    all_tests = tests()
    lines = ["# Test coverage by check", "",
             "Generated by `scripts/gen_test_map.py`. For each check (see `CHECKS_REFERENCE.md`): the tests whose code mentions its finding ids or calls its module. "
             "**Fakes** = the test replaces the GPU worker, the hub, the model endpoint or the registry with a stand-in; the check's own logic still runs. "
             "A check with no test listed has no direct test.", "",
             "| Check | Stage | Tests (file::name) | Count | Uses fakes |", "|---|---|---|---|---|"]
    gaps = []
    for c in CHECKERS:
        module, _, fn = c.entry.partition(":")
        short = module.rsplit(".", 1)[-1]
        hit = []
        for f, name, body in all_tests:
            ids = [i for i in ID.findall(body) if checker_for(i) is c]
            by_fn = fn not in ("scan", "diff") and re.search(rf"\b{re.escape(fn)}\b", body)
            by_module = short not in ("inspectors", "pipeline", "engine") and re.search(rf"\b{re.escape(short)}\b", body)
            if ids or by_fn or by_module:
                hit.append((f, name, bool(FAKES.search(body))))
        shown = "<br>".join(f"`{f}::{n}`" for f, n, _ in hit[:6]) + (f"<br>… {len(hit) - 6} more" if len(hit) > 6 else "")
        lines.append(f"| {c.name} | {c.stage} | {shown or '**none**'} | {len(hit)} | {sum(1 for *_, k in hit if k)} of {len(hit)} |")
        if not hit:
            gaps.append(c.name)
    lines += ["", f"Checks with no direct test: {', '.join(gaps) if gaps else 'none'}."]
    (ROOT / "docs" / "TEST_COVERAGE.md").write_text("\n".join(lines) + "\n")
    print("wrote docs/TEST_COVERAGE.md; checks with no direct test:", gaps or "none")


if __name__ == "__main__":
    main()
