"""Writes docs/FINAL_TEST_MATRIX.md from the real registry (lineage.intake.inspectors.INSPECTORS), the catalogue, the fixture matrix
(docs/check_matrix.json, produced by scripts/check_matrix.py running the real pipeline) and a grep of tests/. Run: uv run python scripts/gen_final_matrix.py"""
from __future__ import annotations

import json
import re
from collections import defaultdict
from pathlib import Path

import lineage.intake.inspectors as insp
from lineage.catalog import CHECKERS

ROOT = Path(__file__).resolve().parent.parent
tests = {p: p.read_text(errors="replace") for p in (ROOT / "tests").rglob("test_*.py")}
fired = json.loads((ROOT / "docs" / "check_matrix.json").read_text())
by_key = {c.key: c for c in CHECKERS}
KEY = {"model_pickle": "pickle", "model_config": "config", "model_tokenizer": "tokenizer", "model_chat_template": "template", "dataset_format": "data_format",
       "dataset_pii": "pii", "dataset_stats": "data_stats", "package_osv": "osv", "package_baseline": "pkg_baseline", "package_capabilities": "capabilities",
       "package_taint": "taint", "package_rules": "rules", "tool_description": "tool_desc", "tool_intent": "tool_intent", "dataset_v2": "data_poison",
       "dataset_upstream_diff": "data_diff", "local_parent_diff": "parent_id", "package_dependency_closure": "pkg_deps",
       "package_provenance": "pkg_provenance", "gpu_weights": "spectral", "gpu_code_review": "llm_code", "gpu_card_review": "llm_card",
       "signed_passport": "signature", "origin_check": "origin", "publisher_policy": "publisher", "parent_chain": "parents", "release_age": "cooldown", "licence": "licence"}
by_fn = {fn: by_key[k] for fn, k in KEY.items() if k in by_key}
MOCKED = {"gpu_weights", "gpu_code_review", "gpu_card_review"}  # the worker / model is faked in every test: see FINAL_BLOCKERS.md
NOT_RUN_HERE = {"gpu_weights": "needs the GPU worker (LINEAGE_GPU_URL)", "gpu_code_review": "needs NVIDIA_API_KEY or a reviewer worker",
                "gpu_card_review": "needs NVIDIA_API_KEY or a reviewer worker"}
rows = defaultdict(lambda: {"types": set(), "stages": set()})
for (kind, stage), fns in insp.INSPECTORS.items():
    for name, fn in fns:
        r = rows[name]; r["types"].add(kind); r["stages"].add(stage); r["mod"] = fn.__module__
out = ["# Final test matrix: every registered check", "",
       "Generated by `scripts/gen_final_matrix.py` from the live registry. Status: **PASS** = the real implementation produced its findings on a fixture through the real pipeline (`scripts/check_matrix.py`); **UNIT-ONLY** = tests reference it, no fixture run; **MOCKED** = every test fakes the worker or model; **NOT-RUN** = needs a service this environment does not have; **UNVERIFIED** = no test or run found. 'Demo' = it appears in the scripted demo (`examples/demo_scenario.sh`) with a real result.", "",
       "| Check (function) | Types | Stage | Source | Catalogue name | Finding ids | Fixture run | Tests that reference it | Status | Note |", "|---|---|---|---|---|---|---|---|---|---|"]
for name in sorted(rows, key=lambda n: (sorted(rows[n]["stages"])[0], n)):
    r = rows[name]; c = by_fn.get(name)
    key = c.key if c else None
    hits = [p.name for p, t in tests.items() if re.search(rf"\b{re.escape(name)}\b", t) or (c and any(pre in t for pre in c.prefixes))]
    fx = sorted({f.split(" ")[0] for v in (fired.get(key) or {}).values() for f in v}) if key else []
    status = "NOT-RUN" if name in NOT_RUN_HERE else "PASS" if fx else "UNIT-ONLY" if hits else "UNVERIFIED"
    if name in MOCKED:
        status = "MOCKED (and NOT-RUN here)"
    note = NOT_RUN_HERE.get(name, "")
    if name == "signed_passport":
        status, note = "PASS", "demo step 9: trust becomes 'recorded' only through a verified in-scope passport; tests/test_signature_scope.py (invalid, untrusted, revoked, out-of-scope, malformed, multi-key)"
    if name == "hub_parent":
        note = "fake-hub tests only; in the demo no base is named so it reports NO_CLAIMED_BASE; never run against the real Hugging Face"
    if name == "package_osv":
        note = "PASS used the shipped snapshot; the live OSV API was unreachable here and the scripted demo shows 'did not run'"
    types = "all" if "*" in r["types"] else ", ".join(sorted(r["types"]))
    out.append(f"| `{name}` | {types} | {', '.join(sorted(r['stages']))} | `{r['mod'].replace('lineage.', '')}` | {c.name if c else '-'} | {', '.join(c.prefixes) if c else '-'} | {', '.join(fx[:3]) + ('…' if len(fx) > 3 else '') if fx else 'no'} | {len(hits)} file(s): {', '.join(sorted(hits)[:3])} | {status} | {note} |")
out += ["", "Not registered scanners that the pipeline still performs (not in the registry, so not in the table above): S1 hashing and passport discovery (`pipeline._identify`), S0 acquisition (`pipeline._s0`, `intake/fetch.py`), declared parents (`pipeline._declared_parents`), policy rules (`policy/engine.py`: banned capability, blocked publisher, vulnerability ceiling, PII, licence, trust minimum, human approval, failed check), the notary and spectral calls inside `gpu_weights`, and the MCP gateway (`mcp_gateway/`, runtime, not intake).", ""]
(ROOT / "docs" / "FINAL_TEST_MATRIX.md").write_text("\n".join(out))
print(len(rows), "registered checks")
