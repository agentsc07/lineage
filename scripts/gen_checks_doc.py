"""Write docs/CHECKS_REFERENCE.md from the catalogue (lineage/catalog.py), the source of each checker and docs/check_matrix.json.

    uv run python scripts/check_matrix.py && uv run python scripts/gen_checks_doc.py
"""
from __future__ import annotations

import importlib
import inspect
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from lineage.catalog import CHECKERS, STAGE_NAMES  # noqa: E402

ID = re.compile(r'"((?:PKG|MODEL|DATA|TOOL|PROV|INTEGRITY|INTAKE|POLICY|LLM|CHECK|SCANNER|GPU)\.[A-Z0-9_.]*[A-Z0-9_])"')
MAX_LINES = 40
# Checks that cannot fire in the matrix (no GPU worker, no API key, no hub) and where their behaviour is exercised instead.
NOT_IN_MATRIX = {
    "spectral": "tests/test_intake_pipeline.py (fake worker); gpu_worker/weights_api.py tests need torch (tests/test_gpu_weights.py, run on the GPU machine)",
    "behaviour": "tests/test_intake_pipeline.py (fake worker); tests/test_gpu_behaviour_notary.py needs torch",
    "notary": "tests/test_intake_pipeline.py::test_notary_mismatch_flagged (fake worker)",
    "llm_code": "tests/test_inspect_llm_review.py and tests/test_hosted_reviewer.py (stubbed model endpoint); no live model call in the suite",
    "llm_card": "tests/test_intake_pipeline.py (fake worker), tests/test_hosted_reviewer.py (stubbed endpoint)",
    "origin": "tests/test_origin.py (fake hub); real hub only with LINEAGE_TEST_REAL_HUB=1",
    "signature": "tests/test_signature_scope.py, tests/test_intake_pipeline.py",
    "parents": "tests/test_intake_pipeline.py", "parent_id": "tests/test_hub_parent.py, tests/test_intake_pipeline.py (needs an admitted model or a named base on a hub)",
    "pkg_provenance": "tests/test_inspect_package_meta.py (needs PyPI metadata)", "osv": "tests/test_inspect_package_meta.py (offline snapshot)",
    "pkg_baseline": "needs network", "pkg_deps": "tests/test_graph_monitor.py", "data_diff": "tests/test_dataset_v2.py (needs an earlier version)",
    "licence": "tests/test_facts.py", "publisher": "tests/test_facts.py", "tokenizer": "tests/test_inspect_tokenizer_template.py (diff part needs a base tokenizer)",
}


def snippet(entry: str) -> str:
    module, _, fn = entry.partition(":")
    try:
        src = inspect.getsource(getattr(importlib.import_module(module), fn)).rstrip().splitlines()
    except (OSError, TypeError, AttributeError):
        return ""
    cut = src[:MAX_LINES]
    return "\n".join(cut) + (f"\n    # ... {len(src) - MAX_LINES} more lines in {module.replace('.', '/')}.py" if len(src) > MAX_LINES else "")


def main() -> None:
    matrix = json.loads((ROOT / "docs" / "check_matrix.json").read_text()) if (ROOT / "docs" / "check_matrix.json").exists() else {}
    out = ["# Checks reference", "",
           "Generated by `scripts/gen_checks_doc.py` from `lineage/catalog.py`, the checkers' source and `docs/check_matrix.json`. Do not edit by hand.", "",
           "Each section is one check: what it looks for, how, exactly what it reads, the finding codes it can produce, the first lines of the code that runs it, "
           "and where it was seen firing. \"Seen firing\" comes from `scripts/check_matrix.py`, which runs the real pipeline offline on inert fixtures "
           "(no GPU, no API key). Checks that need a GPU, an API key or a hub cannot fire there; the line \"Exercised by\" says which test covers them.", ""]
    for stage in ("S1", "S2", "S3", "S4", "S5"):
        group = [c for c in CHECKERS if c.stage == stage]
        if not group:
            continue
        out += [f"## {stage} {STAGE_NAMES.get(stage, '')}", ""]
        for c in group:
            module = c.entry.partition(":")[0]
            try:
                src = Path(importlib.import_module(module).__file__).read_text()
                ids = sorted({i for i in ID.findall(src) if any(i.startswith(p) for p in c.prefixes)})
            except Exception:  # noqa: BLE001
                ids = []
            seen = matrix.get(c.key, {})
            out += [f"### {c.name}", "",
                    f"- **Looks for:** {c.detects}", f"- **How:** {c.how}", f"- **Reads:** {c.reads}", f"- **Needs:** {c.needs}",
                    f"- **Applies to:** {', '.join(c.types)}", f"- **Code:** `{c.entry}`",
                    f"- **Finding codes:** {', '.join(f'`{i}`' for i in ids) or '(see the code)'}"]
            if seen:
                out.append("- **Seen firing on (real run, offline):** " + "; ".join(f"{fx} → {', '.join(sorted({x.split(' ')[0] for x in v}))}" for fx, v in seen.items()))
            if c.key in NOT_IN_MATRIX:
                out.append(f"- **Exercised by:** {NOT_IN_MATRIX[c.key]}")
            s = snippet(c.entry)
            if s:
                out += ["", "```python", s, "```"]
            out.append("")
    (ROOT / "docs" / "CHECKS_REFERENCE.md").write_text("\n".join(out))
    print("wrote docs/CHECKS_REFERENCE.md", len(out), "lines")


if __name__ == "__main__":
    main()
